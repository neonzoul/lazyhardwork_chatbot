'use strict';
// Guards the generated knowledge pack (design-lay-v2.md §8): hand edits, duplicate ids, banned content,
// price wording, and the loader contract. The pack is committed; these tests read it as-is.
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { loadPack, activePromotions, parseSections } = require('../../src/brain/kb');

const KNOWLEDGE = path.join(__dirname, '..', '..', 'knowledge');
const manifest = JSON.parse(fs.readFileSync(path.join(KNOWLEDGE, 'kb-manifest.json'), 'utf8'));
const pack = loadPack(KNOWLEDGE);

const PACK_FILES = ['kb/about.md', 'kb/offer.md', 'kb/fit-map.md', 'kb/process.md', 'kb/faq.md', 'kb/examples.md', 'kb/benefits.md', 'kb/policies.md', 'promotions.yaml'];

test('manifest lists every pack file and the hashes match the bytes on disk (hand-edit detection)', () => {
  for (const file of PACK_FILES) {
    const entry = manifest.outputs[file];
    assert.ok(entry, `manifest has no entry for ${file}`);
    const text = fs.readFileSync(path.join(KNOWLEDGE, file), 'utf8');
    const sha = crypto.createHash('sha256').update(text, 'utf8').digest('hex');
    assert.equal(sha, entry.sha256, `${file} differs from the manifest — it was edited by hand; run npm run kb:build`);
    assert.ok(Array.isArray(entry.sources) && entry.sources.length > 0, `${file} has no sources recorded`);
    for (const src of entry.sources) assert.match(entry.source_sha256[src] || '', /^[0-9a-f]{64}$/, `${file}: no sha for source ${src}`);
    assert.ok(entry.built_at, `${file}: no built_at`);
  }
  assert.equal(typeof manifest.faq_approved, 'boolean');
});

test('every generated markdown file starts with the kb-build header comment', () => {
  for (const file of PACK_FILES.filter((f) => f.endsWith('.md'))) {
    const text = fs.readFileSync(path.join(KNOWLEDGE, file), 'utf8');
    assert.match(text.split('\n')[0], /^<!-- generated by kb-build on \d{4}-\d{2}-\d{2}T.* from .+ — do not edit; run npm run kb:build -->$/, file);
  }
});

test('every section id is unique across the pack and matches the manifest', () => {
  const seen = new Map();
  for (const [name, text] of Object.entries(pack.files)) {
    for (const s of parseSections(name, text)) {
      assert.ok(!seen.has(s.id), `duplicate section id ${s.id} in ${name} and ${seen.get(s.id)}`);
      seen.set(s.id, name);
    }
    const listed = manifest.outputs[`kb/${name}`].sections;
    assert.deepEqual(parseSections(name, text).map((s) => s.id), listed, `${name}: manifest section list is stale`);
  }
  assert.ok(seen.size > 60, `expected a populated pack, got ${seen.size} sections`);
});

test('banned content never appears anywhere in the pack', () => {
  const banned = [/181/, /36 ราย/, /ลดคน/, /แทนพนักงาน/, /ประหยัดค่าแรง/, /@/, /Sprint/, /15,000 \+/];
  for (const file of PACK_FILES) {
    const text = fs.readFileSync(path.join(KNOWLEDGE, file), 'utf8');
    for (const re of banned) assert.doesNotMatch(text, re, `${file} contains banned pattern ${re}`);
  }
});

test('every offer.*.T* section states a starting price with ราคาเริ่มต้น and the price sentence', () => {
  const tierSections = [...pack.sections.values()].filter((s) => /^offer\.[A-C]\d\.T\d$/.test(s.id));
  assert.ok(tierSections.length >= 14, `expected the A1–A4/C1 tier sections, got ${tierSections.length}`);
  for (const s of tierSections) {
    assert.match(s.text, /ราคาเริ่มต้น [\d,]+ บาท/, `${s.id} has no "ราคาเริ่มต้น N บาท"`);
    assert.match(s.text, /ราคาที่เห็นคือราคาเริ่มต้น ปรับตามขอบเขตจริงหลังคุย/, `${s.id} lacks the price sentence`);
  }
  // every THB figure in the offer file is introduced as a starting price (no bare prices)
  const offer = pack.files['offer.md'].split('\n').filter((l) => !l.startsWith('|'));
  for (const line of offer) {
    const bare = line.match(/(?<!ราคาเริ่มต้น )(?<!ราคาเริ่มต้น \d{1,3},)\b\d{1,3}(,\d{3})+ บาท/g);
    if (bare) assert.ok(/ราคาเริ่มต้น/.test(line), `offer.md has a price without ราคาเริ่มต้น on its line: ${line}`);
  }
});

test('the phone number appears only in about.contact-policy and faq.talk-now; no email anywhere', () => {
  const allowed = new Set(['about.contact-policy', 'faq.talk-now']);
  for (const s of pack.sections.values()) {
    if (allowed.has(s.id)) continue;
    assert.ok(!s.text.replace(/[\s-]/g, '').includes('0955691674'), `${s.id} contains the phone number`);
  }
  assert.ok(pack.sections.get('about.contact-policy').text.includes('095 569 1674'));
});

test('loader returns the FAQ ids verbatim with draft flags matching the approval state', () => {
  const faqIds = manifest.outputs['kb/faq.md'].sections;
  assert.ok(faqIds.length >= 25, `expected 25–40 FAQ items, got ${faqIds.length}`);
  for (const id of faqIds) {
    assert.match(id, /^faq\.[a-z0-9-]+$/);
    const s = pack.sections.get(id);
    assert.ok(s, `loader lost ${id}`);
    assert.equal(s.file, 'faq.md');
    assert.ok(s.text.length > 20, `${id} has no answer text`);
    if (!manifest.faq_approved) assert.equal(s.draft, true, `${id} must be flagged draft until Mos approves`);
  }
  for (const must of ['faq.data-safety', 'faq.human-or-bot', 'faq.talk-now', 'faq.discount']) assert.ok(pack.sections.has(must), must);
});

test('loader exposes the expected top-level sections, titles and the fit map', () => {
  for (const id of ['about.proof', 'about.contact-policy', 'offer.overview', 'offer.A2', 'offer.A2.T1', 'offer.A2.care', 'offer.A2.add-channel', 'offer.T4', 'fit.chat-overload', 'fit.data-scattered', 'fit.repetitive-work', 'fit.ai-knows-my-work', 'fit.where-to-start', 'process.steps', 'examples.carousel', 'examples.demo-cafe', 'examples.demo-clinic', 'benefits.overview', 'benefits.osmep-bds-core', 'policies.ai-disclosure', 'policies.banned-claims', 'policies.privacy']) {
    assert.ok(pack.sections.has(id), `missing section ${id}`);
  }
  assert.equal(pack.sections.get('offer.A2.T1').title, 'A2 ลองก่อน — ตอบให้จบ');
  assert.equal(pack.sections.get('offer.C1.T1').title, 'C1 ลองก่อน — AI Business Review');
  assert.match(pack.sections.get('about.proof').text, /Fastwork 4\.9★/);
  for (const id of ['fit.chat-overload', 'fit.data-scattered', 'fit.repetitive-work', 'fit.ai-knows-my-work', 'fit.where-to-start']) {
    assert.match(pack.sections.get(id).text, /ราคาเริ่มต้น [\d,]+ บาท/, `${id} lacks the ledger price line`);
  }
  // benefits: caveat line on every entry
  for (const s of pack.sections.values()) {
    if (/^benefits\.(?!overview)/.test(s.id)) assert.match(s.text, /อาจใช้สิทธิ์ได้ ต้องตรวจสอบกับหน่วยงานก่อน/, `${s.id} lacks the caveat line`);
  }
});

test('activePromotions filters by date and treats undated entries as inactive', () => {
  assert.deepEqual(activePromotions(new Date('2026-10-17'), pack.promotions), []); // file is empty today
  const sample = [
    { id: 'P1', card: 'A4', tier: 'T1', valid_from: '2026-11-01', valid_to: '2026-11-30' },
    { id: 'P2', card: 'A2', tier: 'T1', valid_from: '2026-10-01', valid_to: '2026-10-17' },
    { id: 'P3', card: 'A3' },
  ];
  assert.deepEqual(activePromotions('2026-10-17', sample).map((p) => p.id), ['P2']);
  assert.deepEqual(activePromotions('2026-11-15', sample).map((p) => p.id), ['P1']);
  assert.deepEqual(activePromotions('2026-12-01', sample), []);
});
